"""Photos of places: finding freely licensed candidates, adding the chosen ones as drafts, reviewing them,
and hosting our own resized copies.

Attribution is never typed by hand. A researcher picks a candidate by its key, and the author, license,
and source come from the source's own metadata, as coordinates come from Wikidata and OpenStreetMap.

Sources, in order: the place's Wikidata image (P18) and Commons category (P373), Commons files taken
nearby (which include millions of Geograph photos at full size, and scans from archives), Geograph in
Britain and Ireland, and Flickr, whose "no known copyright restrictions" photos come from archives and
libraries. Flickr needs a free API key (PSST_FLICKR_KEY in ~/.config/psst/env) and is skipped without one.
Only free licenses are accepted: public domain, CC0, CC BY, and CC BY-SA. Wikipedia's non-free files
aren't on Commons, and files Commons marks as AI-generated are refused.
"""

